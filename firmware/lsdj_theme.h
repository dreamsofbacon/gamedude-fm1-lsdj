/* CUSTOM: set from the web page (firmware/lsdj_link.h THEME_SET), kept in the
   save store; CLASSIC until then. As 8 values: gb[0..3], fg, bg, accent, dim. */
static lsdj_theme_t lsdj_theme_custom = {{0xE7DA, 0x9D50, 0x5308, 0x18E3}, 0xFFFF, 0x18E3, 0xFD20, 0x4208};
static const lsdj_theme_t *lsdj_theme_of(unsigned i) { return i == LSDJ_THEME_CUSTOM ? &lsdj_theme_custom : &lsdj_themes[i % LSDJ_THEME_PRESETS]; }
static void lsdj_theme_to8(const lsdj_theme_t *t, uint16_t c[8]) { for (unsigned i = 0; i < 4; i++) c[i] = t->gb[i]; c[4] = t->fg; c[5] = t->bg; c[6] = t->accent; c[7] = t->dim; }
static void lsdj_theme_from8(lsdj_theme_t *t, const uint16_t c[8]) { for (unsigned i = 0; i < 4; i++) t->gb[i] = c[i]; t->fg = c[4]; t->bg = c[5]; t->accent = c[6]; t->dim = c[7]; }

/* Overlay colours of a theme (byte-swapped for the LCD). The screen colours go to
   the emulator separately (gp_palette_colors), so this stays pure. */
static void lsdj_theme_overlay(const lsdj_theme_t *t) {
    lsdj_ov_col.fg = LSDJ_OV_SWAP(t->fg);
    lsdj_ov_col.bg = LSDJ_OV_SWAP(t->bg);
    lsdj_ov_col.accent = LSDJ_OV_SWAP(t->accent);
    lsdj_ov_col.dim = LSDJ_OV_SWAP(t->dim);
    lsdj_ov_col.dim2 = LSDJ_OV_SWAP(0x9CD3u);
}

/* How far apart two colours look (0 .. ~765): channel distance in 8-bit terms. */
static unsigned lsdj_theme_dist(uint16_t a, uint16_t b) {
    int r = (int)((a >> 11) << 3) - (int)((b >> 11) << 3);
    int g = (int)(((a >> 5) & 63u) << 2) - (int)(((b >> 5) & 63u) << 2);
    int bl = (int)((a & 31u) << 3) - (int)((b & 31u) << 3);
    return (unsigned)((r < 0 ? -r : r) + (g < 0 ? -g : g) + (bl < 0 ? -bl : bl));
}
